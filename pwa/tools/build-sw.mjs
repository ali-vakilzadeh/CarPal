// Service worker bundle (P12.T2). src/sw/sw.ts and its imports → one IIFE script, written as a string constant into
// src/sw/generated/bundle.ts, which the /sw.js route serves behind its config prefix (src/app/sw.js/route.ts).
//   node tools/build-sw.mjs           write the bundle
//   node tools/build-sw.mjs --check   exit 1 when the committed bundle differs from the sources (pnpm check)
// The bundle is committed (like the generated contract types), so typecheck, tests and next build never need a
// separate build step; run this after changing anything under src/sw/.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const pwaDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(pwaDir, 'src', 'sw', 'sw.ts');
const target = join(pwaDir, 'src', 'sw', 'generated', 'bundle.ts');

export async function bundleWorker() {
  const out = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
  });
  const code = out.outputFiles[0].text.trim();
  const hash = createHash('sha256').update(code).digest('hex').slice(0, 16);
  return (
    '// GENERATED by pwa/tools/build-sw.mjs from src/sw/sw.ts. Do not edit; run `pnpm sw:build`.\n' +
    `export const SW_BUNDLE_HASH = '${hash}';\n` +
    `export const SW_BUNDLE = ${JSON.stringify(code)};\n`
  );
}

const check = process.argv.includes('--check');
const text = await bundleWorker();
if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('src/sw/generated/bundle.ts is out of date: run `pnpm sw:build`.');
    process.exit(1);
  }
  console.log('src/sw/generated/bundle.ts is up to date.');
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
  console.log(`wrote src/sw/generated/bundle.ts (${text.length} bytes)`);
}
