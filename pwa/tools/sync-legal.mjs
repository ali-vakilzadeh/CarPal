// Legal texts sync (P13.T7). Docs/Privacy Policy.md and Docs/User Agreement.md are the source of truth; the PWA serves
// them at /<locale>/privacy and /<locale>/terms and in the sign-up "Read" dialogs.
//   node tools/sync-legal.mjs           write src/features/legal/generated/texts.ts
//   node tools/sync-legal.mjs --check   exit 1 when the committed file differs from Docs (part of pnpm check)
// The version accepted at sign-up comes from each text's "Version <x>" line, so the recorded version always names the
// text the visitor could read.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pwaDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = join(pwaDir, '..');

export const SOURCES = {
  privacy: join(repoDir, 'Docs', 'Privacy Policy.md'),
  terms: join(repoDir, 'Docs', 'User Agreement.md'),
};
export const TARGET = join(pwaDir, 'src', 'features', 'legal', 'generated', 'texts.ts');

/** "Effective date: … · Version 1.0 (MVP)" → "1.0" (the contract takes Str<1,20>). */
export function versionOf(markdown, name = 'text') {
  const m = /^Effective date:.*?Version\s+([0-9][0-9A-Za-z.-]{0,19})/m.exec(markdown);
  if (!m) throw new Error(`${name}: no "Effective date: … Version <x>" line`);
  return m[1];
}

export function render(texts) {
  const entries = Object.entries(texts).map(([kind, markdown]) => {
    const clean = markdown.replace(/\r\n?/g, '\n').trimEnd() + '\n';
    return `  ${kind}: {\n    version: ${JSON.stringify(versionOf(clean, kind))},\n    markdown: ${JSON.stringify(clean)},\n  },`;
  });
  return [
    '// Generated by tools/sync-legal.mjs from Docs/Privacy Policy.md and Docs/User Agreement.md. Do not edit;',
    '// run `pnpm legal:sync` after the texts change (pnpm check runs `pnpm legal:check`).',
    'export const LEGAL_TEXTS = {',
    ...entries,
    '} as const;',
    '',
  ].join('\n');
}

function build() {
  return render(Object.fromEntries(Object.entries(SOURCES).map(([k, f]) => [k, readFileSync(f, 'utf8')])));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = build();
  if (process.argv.includes('--check')) {
    // A Windows checkout with core.autocrlf turns the committed LF file into CRLF; compare the content.
    const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== next) {
      console.error('legal:check: src/features/legal/generated/texts.ts is out of date with Docs/ — run `pnpm legal:sync`.');
      process.exit(1);
    }
    console.log('legal:check: legal texts are in sync.');
  } else {
    mkdirSync(dirname(TARGET), { recursive: true });
    writeFileSync(TARGET, next);
    console.log('legal:sync: wrote src/features/legal/generated/texts.ts');
  }
}
