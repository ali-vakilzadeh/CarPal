/** Rewrites contract references to OpenAPI components and Json<Name> to its server-defined component; annotates x-vin. */
function rewrite(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(rewrite);
  if (!node || typeof node !== 'object') return node;
  const o = node as Json;
  if (typeof o['x-server-schema'] === 'string') return { $ref: `${COMPONENT}${o['x-server-schema']}` };
  const out: Json = {};
  for (const [k, v] of Object.entries(o)) {
    if (k === '$ref' && typeof v === 'string') out[k] = v.replace(`${SCHEMA_ID}#/$defs/`, COMPONENT).replace('#/$defs/', COMPONENT);
    else out[k] = rewrite(v);
  }
  if (o['x-vin'] === true && !out.description) out.description = VIN_NOTE;
  if (typeof o['x-external'] === 'string' && EXTERNAL_DOCS[o['x-external']])
    out.externalDocs = { description: o['x-external'], url: EXTERNAL_DOCS[o['x-external']] };
  return out;
}

function fromZod(s: z.ZodType): Schema {
  const { $schema: _drop, ...rest } = z.toJSONSchema(s, { target: 'draft-2020-12' }) as Json;
  return rest;
}

/** One component per variant and the union keyed by the parent's discriminator field. */
function keyedUnion(name: string, on: string, variants: Record<string, Schema>, description: string): Record<string, Schema> {
  const out: Record<string, Schema> = {};
  const mapping: Record<string, string> = {};
  for (const [key, schema] of Object.entries(variants).sort(([a], [b]) => a.localeCompare(b))) {
    out[`${name}.${key}`] = schema;
    mapping[key] = `${COMPONENT}${name}.${key}`;
  }
  out[name] = {
    description,
    anyOf: Object.values(mapping).map(($ref) => ({ $ref })),
    'x-carpal-keyed-by': { field: on, mapping },
  };
  return out;
}

