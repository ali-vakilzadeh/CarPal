const tag = (route: Route, name: string): SecTag | undefined => route.security.tags.find((t) => t.tag === name);
const tokenless = (route: Route) => route.security.principals.some((alt) => alt.some((t) => t.tag === 'PUB' && t.qualifier === 'no token'));
const oauthRoute = (route: Route) => route.host === 'auth' && route.path.startsWith('/oauth/');

function firstSentence(text: string): string {
  const m = /^(.+?[.!?])(\s|$)/.exec(text);
  const s = (m ? m[1]! : text).trim();
  return s.length <= 120 ? s : `${s.slice(0, 117)}…`;
}

function hasVersion(schema: unknown, defs: Record<string, Schema>, depth = 0): boolean {
  if (!schema || typeof schema !== 'object' || depth > 6) return false;
  const s = schema as Json;
  if (typeof s.$ref === 'string') return hasVersion(defs[s.$ref.split('/').pop()!], defs, depth + 1);
  if (s.properties && typeof s.properties === 'object' && 'version' in (s.properties as Json)) return true;
  return Array.isArray(s.allOf) && s.allOf.some((x) => hasVersion(x, defs, depth + 1));
}

function status(op: Operation, implemented: Map<string, string>): string {
  if (DEFERRED_OPERATIONS[op.opId]) return DEFERRED_OPERATIONS[op.opId]!.status;
  if (STORAGE_OPERATIONS[op.opId] && implemented.has(op.opId)) return 'storage-listener';
  return implemented.has(op.opId) ? 'implemented' : 'not-implemented';
}

interface Ctx {
  defs: Record<string, Schema>;
  opSchemas: Record<
    string,
    { input?: Schema; response?: Schema; alternateResponses?: Record<string, Schema>; query: Schema; pathParams: Record<string, Schema> }
  >;
  implemented: Map<string, string>;
}

function operation(op: Operation, route: Route, operationId: string, x: Ctx): Json {
  const s = x.opSchemas[op.opId]!;
  const parameters: Json[] = [];
  for (const p of route.pathParams) parameters.push({ name: p, in: 'path', required: true, schema: rewrite(s.pathParams[p] ?? {}) });
  const q = s.query as { properties?: Record<string, Schema>; required?: string[] };
  for (const [name, schema] of Object.entries(q.properties ?? {}))
    parameters.push({
      name,
      in: 'query',
      required: (q.required ?? []).includes(name),
      schema: rewrite(schema),
      ...(name === 'cursor' ? { description: CURSOR_NOTE } : {}),
    });
  const noToken = tokenless(route);
  parameters.push(ref(noToken && route.method === 'GET' ? 'CarPalClientOptional' : 'CarPalClient'));
  if (!noToken) parameters.push(ref('DPoP'));
  parameters.push(ref('AcceptLanguage'), ref('CarPalTimezone'), ref('CarPalRequestId'));
  const idem = tag(route, 'IDEM');
  if (idem) parameters.push(ref(idem.qualifier ? 'IdempotencyKeyIfNew' : 'IdempotencyKey'));
  const etag = tag(route, 'ETAG');
  if (etag) parameters.push(ref(etag.qualifier ? 'IfMatchIfExists' : 'IfMatch'));
  if (tag(route, 'PURP')) parameters.push(ref('CarPalAccessPurpose'));
  if (tag(route, 'RSN') && route.method === 'DELETE') parameters.push(ref('CarPalReason'));
  if (tag(route, 'ATT')) parameters.push(ref('CarPalAttestation'), ref('CarPalPoW'));

  const out: Json = {
    operationId,
    summary: firstSentence(op.summary),
    description: op.summary + (op.inputNote ? `\n\nInput: ${op.inputNote}` : '') + (op.queryNote ? `\n\nQuery: ${op.queryNote}` : ''),
    tags: [op.module],
    parameters,
  };

  // Request body.
  if (op.inputEncoding === 'json' && s.input) {
    const body = rewrite(s.input) as Json;
    const props = body.properties as Record<string, Json> | undefined;
    if (props?.cursor) props.cursor = { ...props.cursor, description: `${CURSOR_NOTE} Searches page in the body (TR-7).` };
    out.requestBody = { required: true, content: { 'application/json': { schema: body } } };
  } else if (op.inputEncoding === 'form') {
    const schema = op.opId === 'auth.token' ? TOKEN_REQUEST : rewrite(s.input ?? { type: 'object' });
    out.requestBody = { required: true, content: { 'application/x-www-form-urlencoded': { schema } } };
  }

  // Responses.
  const responses: Json = {};
  const success: Json = { description: op.responseNote ?? op.responseType ?? 'OK', headers: { ...TRACE } };
  const headers = success.headers as Json;
  if (op.successStatus === 201 || op.successStatus === 202 || op.successStatus === 302) headers.Location = H('Location');
  if (s.response) {
    success.content = { 'application/json': { schema: rewrite(s.response) } };
    if (hasVersion(s.response, x.defs)) headers.ETag = H('ETag');
  }
  if (idem) headers['Idempotent-Replayed'] = H('Idempotent-Replayed');
  responses[String(op.successStatus)] = success;
  for (const [st, schema] of Object.entries(s.alternateResponses ?? {}))
    responses[st] = {
      description: (op.alternateResponses ?? []).find((a) => String(a.status) === st)?.type ?? 'OK',
      headers: { ...TRACE, Location: H('Location') },
      content: { 'application/json': { schema: rewrite(schema) } },
    };
  const specific = new Map<number, string[]>();
  for (const e of op.errors) specific.set(e.status, [...(specific.get(e.status) ?? []), e.code]);
  if (oauthRoute(route)) {
    for (const st of [...specific.keys()].sort())
      responses[String(st)] = {
        description: `OAuth error: ${specific.get(st)!.join(', ')}`,
        content: { 'application/json': { schema: { $ref: `${COMPONENT}ProtocolError` } } },
        'x-carpal-error-codes': specific.get(st),
      };
  }
  for (const st of [...new Set([...COMMON_STATUSES, ...(oauthRoute(route) ? [] : specific.keys())])].sort((a, b) => a - b)) {
    if (responses[String(st)]) continue;
    const own = oauthRoute(route) ? [] : (specific.get(st) ?? []);
    responses[String(st)] = own.length
      ? problemResponse(st, [...own, ...commonCodes.filter((c) => c.status === st).map((c) => c.code)])
      : { $ref: `#/components/responses/Problem${st}` };
  }
  if (DEFERRED_OPERATIONS[op.opId]) responses['501'] = problemResponse(501, ['NOT_IMPLEMENTED']);
  out.responses = responses;
  out.security = noToken ? [] : [{ dpop: [] }, { bffBearer: [], bffMutualTls: [] }];

  out['x-carpal-op-id'] = op.opId;
  out['x-carpal-host'] = route.host;
  out['x-carpal-scope'] = route.scope;
  out['x-carpal-sec'] = op.sec;
  out['x-carpal-security'] = route.security;
  out['x-carpal-status'] = status(op, x.implemented);
  if (DEFERRED_OPERATIONS[op.opId]) out['x-carpal-status-reason'] = DEFERRED_OPERATIONS[op.opId]!.reason;
  if (op.emits.length) out['x-carpal-emits'] = op.emits.map((e) => e.event);
  out['x-carpal-contract'] = { section: op.section, line: op.line };
  return out;
}

/** The signed storage PUT (media.upload_put): not an API route; its URL comes whole from UploadTicket.url. */
function storageOperation(op: Operation, x: Ctx): Json {
  return {
    operationId: op.opId,
    summary: firstSentence(op.summary),
    description:
      `${op.summary}\n\nNever build this URL: PUT the bytes to UploadTicket.url exactly as returned by media.upload_init, ` +
      'with exactly the UploadTicket.headers (Content-Type, Content-Length, x-amz-checksum-sha256). The path and query are opaque and signed; ' +
      'no Authorization header and no cookies.',
    tags: [op.module],
    parameters: [
      { name: 'object_key', in: 'path', required: true, schema: { type: 'string' }, description: 'Opaque part of UploadTicket.url.' },
      hdr('Content-Length', true, { type: 'integer', minimum: 1 }, 'As in UploadTicket.headers.'),
      hdr(
        'x-amz-checksum-sha256',
        true,
        { type: 'string', pattern: '^[A-Za-z0-9+/]{43}=$' },
        'Base64 SHA-256 of the bytes, as declared at media.upload_init.',
      ),
    ],
    requestBody: {
      required: true,
      content: Object.fromEntries(
        ['image/jpeg', 'image/png', 'image/webp', 'video/mp4', 'application/pdf', 'text/csv'].map((m) => [
          m,
          { schema: { type: 'string', format: 'binary' } },
        ]),
      ),
    },
    responses: {
      '200': { description: 'Stored; complete the upload with media.upload_complete.' },
      '400': { description: 'Length or checksum differs from the ticket.' },
      '403': { description: 'Signature invalid or ticket expired (10 minutes).' },
    },
    security: [],
    'x-carpal-op-id': op.opId,
    'x-carpal-host': 'storage',
    'x-carpal-path-template': op.pathTemplate,
    'x-carpal-sec': op.sec,
    'x-carpal-status': status(op, x.implemented),
    'x-carpal-contract': { section: op.section, line: op.line },
  };
}

/** Module tags with the contract section titles ("# 12. Vehicles and Service History — module `vehicle`"). */
function moduleTags(modules: string[]): Json[] {
  const titles = new Map<string, string[]>();
  for (const m of readFileSync(CONTRACT_DOC, 'utf8').matchAll(/^# \d+\. (.+?) — module `([a-z-]+)`/gm))
    titles.set(m[2]!, [...(titles.get(m[2]!) ?? []), m[1]!]);
  return [...new Set(modules)].sort().map((m) => ({
    name: m,
    description: titles.get(m)?.join('; ') ?? (m === 'platform' ? 'Platform operations (40 §22)' : `Module ${m}`),
  }));
}

export function buildOpenApi(): Json {
  const registry = loadRegistry();
  const { root, operations: opSchemas } = loadSchemas() as unknown as {
    root: { $defs: Record<string, Schema> };
    operations: Ctx['opSchemas'];
  };
  const x: Ctx = { defs: root.$defs, opSchemas, implemented: implementedOperations() };
  const schemas: Record<string, Schema> = {};
  for (const [name, def] of Object.entries(root.$defs)) schemas[name] = rewrite(def) as Schema;
  const server = serverSchemas();
  for (const name of Object.keys(server)) if (schemas[name]) throw new Error(`server-defined schema ${name} collides with a contract type`);
  Object.assign(schemas, server);
  const oauthCodes = registry.operations.flatMap((o) => o.errors.filter((e) => /^[a-z_]+$/.test(e.code)).map((e) => e.code));
  schemas.ProtocolError = protocolError(oauthCodes);

  const paths: Record<string, Json> = {};
  for (const op of registry.operations) {
    for (const route of op.routes) {
      const path = route.host === 'storage' ? '/o/{object_key}' : route.path;
      const item = (paths[path] ??= { servers: [SERVERS[route.host]] });
      const operationId = op.routes.length > 1 ? `${op.opId}.${route.scope}` : op.opId;
      item[route.method.toLowerCase()] = route.host === 'storage' ? storageOperation(op, x) : operation(op, route, operationId, x);
    }
  }
  const sortedPaths = Object.fromEntries(
    Object.keys(paths)
      .sort()
      .map((p) => [p, paths[p]]),
  );

  const responses: Record<string, Json> = {};
  for (const st of COMMON_STATUSES)
    responses[`Problem${st}`] = problemResponse(
      st,
      commonCodes.filter((c) => c.status === st).map((c) => c.code),
    );

  return {
    openapi: '3.1.0',
    jsonSchemaDialect: 'https://json-schema.org/draft/2020-12/schema',
    info: {
      title: 'CarPal API',
      version: registry.contractVersion,
      summary: 'CarPal MVP API: consumer, business, admin plane and authorization server.',
      description: [
        `Generated from ${registry.source} (contract ${registry.contractVersion}, sha256 ${registry.sourceSha256}); the contract is authoritative.`,
        'Conventions (40 §0-§4): every schema is closed (additionalProperties false); unknown body members are 422 UNKNOWN_FIELD and unknown query parameters 400 UNKNOWN_QUERY_PARAM.',
        'Request bodies are application/json except the OAuth forms of /oauth/* and the raw storage PUT. Personal or location data never appears in URLs (TR-7): searches use POST and page in the body.',
        'Errors are application/problem+json (Problem, RFC 9457) with a stable code; /oauth/* answer RFC 6749 error bodies (ProtocolError). Authorization failures are 404, never 403 (SEC-AZ-2).',
        'x-carpal-sec is the contract sec line (40 §0.4): PUB, USR, ORG(role groups), DRV, STF, LNK, AAL2/AAL3, ATT, IDEM, ETAG, RL, ENT, CNS, FLAG, ASYNC, AUD, RSN, 4EYES, PURP, PII.',
        'Schema keywords: x-node-type (taxonomy node type the id must have), x-conditional (rule of a conditional field), x-locale-config (enabled locales), x-vin (VIN normalization), x-external (standard document).',
        '4EYES operations answer 202 PendingChange until a second staff member approves (admin.four_eyes_decide); ASYNC operations answer 202 Job (jobs.get).',
      ].join('\n\n'),
      'x-carpal-contract-sha256': registry.sourceSha256,
    },
    servers: Object.values(SERVERS),
    tags: moduleTags(registry.operations.map((o) => o.module)),
    paths: sortedPaths,
    components: {
      schemas,
      parameters: PARAMETERS,
      headers: RESPONSE_HEADERS,
      responses,
      securitySchemes: {
        dpop: {
          type: 'http',
          scheme: 'DPoP',
          description:
            'Mobile app: Authorization: DPoP <access_token> with a DPoP proof header (RFC 9449); EdDSA access tokens, audience per host.',
        },
        bffBearer: {
          type: 'http',
          scheme: 'bearer',
          description: 'BFFs: Authorization: Bearer <access_token>, bound to the client certificate (RFC 8705).',
        },
        bffMutualTls: { type: 'mutualTLS', description: 'BFF client certificate (RFC 8705).' },
        oidc: {
          type: 'openIdConnect',
          openIdConnectUrl: 'https://id.carpal.app/.well-known/openid-configuration',
          description: 'Where tokens come from: authorization code + PKCE (S256), refresh rotation, the anonymous grant (SEC-AU-14).',
        },
      },
    },
  };
}

