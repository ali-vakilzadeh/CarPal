/** Structural checks: references resolve, ids unique, path parameters declared, every schema compiles (JSON Schema 2020-12). */
export function structuralProblems(doc: Json): string[] {
  const problems: string[] = [];
  const components = doc.components as Record<string, Record<string, unknown>>;
  const walk = (node: unknown, at: string): void => {
    if (Array.isArray(node)) return node.forEach((n, i) => walk(n, `${at}/${i}`));
    if (!node || typeof node !== 'object') return;
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string') {
        const m = /^#\/components\/([a-zA-Z]+)\/(.+)$/.exec(v);
        if (!m || !components[m[1]!]?.[m[2]!]) problems.push(`${at}: unresolved $ref ${v}`);
      } else walk(v, `${at}/${k}`);
    }
  };
  walk(doc, '#');
  const ids = new Set<string>();
  const ajv = new Ajv2020({ strict: false, validateFormats: false, allErrors: false });
  ajv.addSchema({ $id: 'urn:carpal:openapi', components: { schemas: components.schemas } });
  const compile = (schema: unknown, at: string) => {
    try {
      ajv.compile(JSON.parse(JSON.stringify(schema).replaceAll('"#/components/', '"urn:carpal:openapi#/components/')));
    } catch (e) {
      problems.push(`${at}: ${(e as Error).message}`);
    }
  };
  for (const [name, schema] of Object.entries(components.schemas!)) compile(schema, `schema ${name}`);
  for (const [path, item] of Object.entries(doc.paths as Record<string, Json>)) {
    const templ = [...path.matchAll(/\{([a-z_]+)\}/g)].map((m) => m[1]!);
    for (const [method, o] of Object.entries(item)) {
      if (method === 'servers') continue;
      const op = o as Json;
      const id = op.operationId as string;
      if (ids.has(id)) problems.push(`duplicate operationId ${id}`);
      ids.add(id);
      const declared = (op.parameters as Json[]).filter((p) => p.in === 'path').map((p) => p.name as string);
      if (templ.join() !== declared.join())
        problems.push(`${method.toUpperCase()} ${path}: path parameters ${declared} vs template ${templ}`);
      for (const p of op.parameters as Json[]) if (p.schema) compile(p.schema, `${id} parameter ${p.name as string}`);
      const body = (op.requestBody as { content?: Record<string, { schema?: unknown }> } | undefined)?.content;
      for (const [type, c] of Object.entries(body ?? {})) if (c.schema) compile(c.schema, `${id} body ${type}`);
      for (const [st, r] of Object.entries(op.responses as Record<string, { content?: Record<string, { schema?: unknown }> }>))
        for (const c of Object.values(r.content ?? {})) if (c.schema) compile(c.schema, `${id} response ${st}`);
    }
  }
  return problems;
}

/** The file against the router (every host's RouteTable) and the registry: same operations, methods, paths and hosts. */
export function routerProblems(doc: Json): string[] {
  const problems: string[] = [];
  const registry = loadRegistry();
  if ((doc.info as Json)['x-carpal-contract-sha256'] !== registry.sourceSha256) problems.push('contract sha256 differs from the registry');
  const documented = new Map<string, string>();
  for (const [path, item] of Object.entries(doc.paths as Record<string, Json>))
    for (const [method, o] of Object.entries(item)) {
      if (method === 'servers') continue;
      const op = o as Json;
      documented.set(`${op['x-carpal-host'] as string} ${method.toUpperCase()} ${path}`, op['x-carpal-op-id'] as string);
    }
  const served = new Map<string, string>();
  for (const host of ['api', 'admin-api', 'auth'] as const)
    for (const e of new RouteTable(host).entries) served.set(`${host} ${e.route.method} ${e.route.path}`, e.op.opId);
  for (const op of registry.operations)
    for (const r of op.routes) if (r.host === 'storage') served.set(`storage ${r.method} /o/{object_key}`, op.opId);
  for (const [k, id] of served)
    if (documented.get(k) !== id)
      problems.push(`router ${k} (${id}) is ${documented.has(k) ? `documented as ${documented.get(k)}` : 'not documented'}`);
  for (const [k, id] of documented) if (!served.has(k)) problems.push(`documented ${k} (${id}) is not served`);
  const registryRoutes = registry.operations.reduce((n, o) => n + o.routes.length, 0);
  if (documented.size !== registryRoutes) problems.push(`${documented.size} documented routes, registry has ${registryRoutes}`);
  return problems;
}

export function renderOpenApi(): string {
  return toYaml(buildOpenApi(), HEADER);
}

function main(): void {
  const check = process.argv.includes('--check');
  const doc = buildOpenApi();
  const content = toYaml(doc, HEADER);
  const problems = [...structuralProblems(doc), ...routerProblems(doc)];
  const rel = relative(backendDir, OPENAPI_FILE).replace(/\\/g, '/');
  const paths = Object.values(doc.paths as Record<string, Json>).reduce((n, i) => n + Object.keys(i).length - 1, 0);
  console.log(
    `OpenAPI 3.1: ${paths} operations on ${Object.keys(doc.paths as Json).length} paths, ${Object.keys((doc.components as Json).schemas as Json).length} schemas`,
  );
  if (problems.length) {
    for (const p of problems.slice(0, 50)) console.error(`  ${p}`);
    console.error(`${problems.length} problem(s) in the OpenAPI document.`);
    process.exit(1);
  }
  const current = existsSync(OPENAPI_FILE) ? readFileSync(OPENAPI_FILE, 'utf8').replace(/\r\n/g, '\n') : null;
  if (check) {
    if (current !== content) {
      console.error(`${rel} is out of date. Run pnpm openapi:generate.`);
      process.exit(1);
    }
    console.log(`${rel} is up to date and matches the router and the registry.`);
    return;
  }
  if (current !== content) {
    mkdirSync(dirname(OPENAPI_FILE), { recursive: true });
    writeFileSync(OPENAPI_FILE, content);
  }
  console.log(`Wrote ${rel}`);
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('tools/contract/openapi.ts')) main();
