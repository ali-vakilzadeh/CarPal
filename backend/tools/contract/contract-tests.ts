// pnpm contract:tests — generates the contract sweep suites (S9b, 40
// Appendix C, L22): one file per module under apps/testing/contract/generated/
// listing every HTTP route of the module's operations from operations.json.
// The suites run apps/testing/contract/runner.ts with the module's resolvers
// (apps/testing/contract/resolvers/<module>.ts). `--check` fails when a file
// is stale (part of pnpm contract:check), so a contract change cannot skip
// the sweep.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadRegistry, type OperationRegistry } from '#libs/contract/index.js';
import { backendDir } from '../db/config.js';

export const SUITE_DIR = join(backendDir, 'apps', 'testing', 'contract', 'generated');

const fileOf = (module: string) => `${module}.contract.int.test.ts`;

/** The generated suites, file name → content. */
export function contractSuites(registry: OperationRegistry = loadRegistry()): Map<string, string> {
  const modules = [...new Set(registry.operations.map((o) => o.module))].sort();
  const out = new Map<string, string>();
  for (const module of modules) {
    const routes = registry.operations
      .filter((o) => o.module === module)
      .flatMap((o) => o.routes.filter((r) => r.host !== 'storage').map((r) => [o.opId, r.method, r.path] as const));
    const lines = [
      `// GENERATED by tools/contract/contract-tests.ts from libs/contract/generated/operations.json. Do not edit.`,
      `// Contract sweep of the ${module} module (S9b, 40 Appendix C): ${routes.length} routes.`,
      `import { resolvers } from '../resolvers/${module}.js';`,
      `import { contractSuite } from '../runner.js';`,
      ``,
      `contractSuite('${module}', resolvers, [`,
      ...routes.map(([op, method, path]) => `  ['${op}', '${method}', '${path}'],`),
      `]);`,
      ``,
    ];
    out.set(fileOf(module), lines.join('\n'));
  }
  return out;
}

function main(): void {
  const check = process.argv.includes('--check');
  const suites = contractSuites();
  const existing = existsSync(SUITE_DIR) ? readdirSync(SUITE_DIR).filter((f) => f.endsWith('.contract.int.test.ts')) : [];
  const stale = [
    ...[...suites].filter(([f, content]) => !existing.includes(f) || readFileSync(join(SUITE_DIR, f), 'utf8') !== content).map(([f]) => f),
    ...existing.filter((f) => !suites.has(f)),
  ];
  if (check) {
    if (stale.length) {
      console.error(`Contract sweep suites are stale: ${stale.join(', ')}. Run pnpm contract:tests.`);
      process.exit(1);
    }
    console.log(`Contract sweep suites up to date (${suites.size} modules).`);
    return;
  }
  mkdirSync(SUITE_DIR, { recursive: true });
  for (const f of existing) if (!suites.has(f)) rmSync(join(SUITE_DIR, f));
  for (const [f, content] of suites) writeFileSync(join(SUITE_DIR, f), content);
  console.log(`Wrote ${suites.size} contract sweep suites to apps/testing/contract/generated (${stale.length} changed).`);
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('tools/contract/contract-tests.ts')) main();
